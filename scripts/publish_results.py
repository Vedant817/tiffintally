"""Generate public numbers exclusively by rescoring saved per-row artifacts."""

import argparse
import html
import json
from pathlib import Path

from scripts.compare import load
from tiffintally.scoring import summarize

ROOT = Path(__file__).resolve().parents[1]
CLAIM = "The saved synthetic results describe the cleaned rules only; they establish neither model superiority nor accuracy on real cook messages."
START = "<!-- measured-results:start -->"
END = "<!-- measured-results:end -->"


def generated():
    table = [
        "| System | Split | Metric | Correct / n | Accuracy | Wilson interval | Source |",
        "|---|---|---|---|---|---|---|",
    ]
    numbers = [
        "# Numerical evidence",
        "",
        "Generated by `scripts/publish_results.py` from saved predictions using the shared scorer.",
        "",
        "| Number | File:key | Script | Code SHA | Date |",
        "|---|---|---|---|---|",
    ]
    summary = {}
    html_rows = []
    for split in ("train", "dev2", "test"):
        source = f"evals/final/regex/{split}.jsonl"
        meta = json.loads((ROOT / f"evals/final/regex/{split}.meta.json").read_text())
        rows = load(ROOT / source)
        report = summarize(rows)
        if report["n"] != meta["n"]:
            raise ValueError("Metadata row count disagrees with predictions")
        summary[split] = report
        for metric in ("strict", "lenient"):
            score = report[metric]
            low, high = score["wilson_95"]
            pct = f"{score['accuracy'] * 100:.1f}%"
            interval = f"{low * 100:.1f} to {high * 100:.1f}"
            cells = [
                "regex",
                split,
                metric,
                f"{score['hits']} / {report['n']}",
                pct,
                interval,
                source,
            ]
            table.append("| " + " | ".join(cells) + " |")
            html_rows.append(
                "<tr>" + "".join(f"<td>{html.escape(cell)}</td>" for cell in cells) + "</tr>"
            )
            numbers.append(
                f"| {pct}; {score['hits']}/{report['n']}; interval {interval} | "
                f"evals/final/public_summary.json:{split}.{metric} | scripts/publish_results.py | "
                f"{meta['code_sha']} | {meta['date']} |"
            )
    text = "\n".join(table)
    body = (
        f"{START}\n\n{CLAIM}\n\n{text}\n\n"
        "Strict compares complete event sets on meal, quantity, action, canonical mods, payment amount and secondary customer. "
        "Lenient compares meal, quantity and action. Unknown mods are wrong. Date, items and review routing are not accuracy fields.\n\n"
        "The legacy synthetic test has known sibling-template leakage and template-authored labels. "
        "dev2 is agent-authored development data; legacy dev is a training subset. "
        "Wilson intervals treat rows as independent and do not correct that leakage. "
        "See docs/KNOWN_LEAKS.md and the per-template comparison output.\n\n"
        "Base, few-shot base, adapter and hosted baselines: NOT RUN (needs approval or credentials). "
        "Gemma baseline: NOT RUN (no GOOGLE_API_KEY in the environment, so there is no hosted-model "
        "run to compare against these rows). "
        "The historical adapter aggregates lack complete per-row outputs and cannot be independently rescored. "
        "Real/human-written holdout: NOT RUN (verified human provenance and labels missing). "
        f"Cost: NOT MEASURED.\n\n{END}"
    )
    results = (
        "# Results\n\n" + body + "\n\nPrevious reported results and retractions are retained in "
        "`docs/review/RESULTS-before-round4.md` and `evals/retracted/`. "
        "They are historical logs, not current reproducible model measurements.\n"
    )
    readme_path = ROOT / "README.md"
    readme = readme_path.read_text(encoding="utf-8")
    if START in readme:
        before, rest = readme.split(START, 1)
        _, after = rest.split(END, 1)
        readme = before + body + after
    else:
        readme += "\n" + body + "\n"
    dashboard = (
        "<!doctype html><html lang=en><meta charset=utf-8><meta name=viewport content='width=device-width,initial-scale=1'>"
        "<title>TiffinTally saved results</title><style>body{font:16px/1.5 system-ui;margin:32px;max-width:1200px;color:#18352a}"
        "table{border-collapse:collapse;width:100%}td,th{text-align:left;border-bottom:1px solid #ccc;padding:12px}"
        ".scroll{overflow-x:auto}small{color:#555}</style><h1>Saved rules results</h1>"
        f"<p>{CLAIM}</p><div class=scroll><table><thead><tr>"
        + "".join(
            f"<th>{cell}</th>"
            for cell in (
                "System",
                "Split",
                "Metric",
                "Correct / n",
                "Accuracy",
                "Wilson interval",
                "Source",
            )
        )
        + "</tr></thead><tbody>"
        + "".join(html_rows)
        + "</tbody></table></div>"
        "<p>Strict: meal, quantity, action, canonical dietary mods, payment amount and secondary customer. "
        "Lenient: meal, quantity and action. Entire event sets are compared.</p>"
        "<p>Known sibling leakage and synthetic labels limit inference. Wilson intervals assume independent rows. "
        "dev2 is development data. Hosted baselines and human holdout: NOT RUN. Cost: NOT MEASURED.</p>"
        "<small>Generated from saved predictions by scripts/publish_results.py. No live model ran to render this page.</small></html>\n"
    )
    numbers += [
        "",
        "Historical percentages in the untouched submission draft and old decision notes are inventoried in "
        "`evals/final/legacy_claims.json` with UNVERIFIED status. They are not promoted to measurements. "
        "The numerical checker rejects new unregistered claims and checks the generated public tables byte for byte.",
    ]
    return {
        "README.md": readme,
        "RESULTS.md": results,
        "evals/dashboard.html": dashboard,
        "docs/NUMBERS.md": "\n".join(numbers) + "\n",
        "evals/final/public_summary.json": json.dumps(summary, indent=2) + "\n",
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    failed = []
    for name, content in generated().items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                failed.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    print("FAIL: " + ", ".join(failed) if failed else "PASS: public tables match saved predictions")
    return bool(failed)


if __name__ == "__main__":
    raise SystemExit(main())
